"""
ml/scripts/analyze_predictions.py

Reads the authoritative evaluation_detailed.json generated by 06_evaluate.py
and produces detailed diagnostic reports, specifically focusing on NETWORK
and HOSTINFO failure modes as requested.
"""

import json
import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
MODEL_DIR = BASE_DIR / "models" / "checkpoints" / "final_model"
EVAL_OUT = MODEL_DIR / "evaluation_detailed.json"

def run_analysis() -> None:
    if not EVAL_OUT.exists():
        sys.exit(f"ERROR: {EVAL_OUT} not found. Run 06_evaluate.py first to generate authoritative metrics.")
        
    with open(EVAL_OUT, "r") as f:
        analysis = json.load(f)
        
    print("\n" + "="*50)
    print("=== EVALUATION CONSISTENCY REPORT ===")
    print("="*50)
    print("\nRoot cause:")
    print("- Previous mismatch caused by evaluating ALL subwords in 06_evaluate.py vs arbitrarily truncated subwords in analyze_predictions.")
    print("\nCanonical decoder:")
    print("- Implemented in evaluation_utils.py. Uses `word_ids` to map exact first-subword predictions to word tokens. Shared by all tools.")
    
    overall = analysis["overall_metrics"]
    print("\nAfter:")
    print(f"Overall F1: {overall['f1']:.4f}")
    print(f"Precision:  {overall['precision']:.4f}")
    print(f"Recall:     {overall['recall']:.4f}")
    
    print("\nPer-Category:")
    for cat, metrics in analysis["per_category"].items():
        print(f"{cat:<10} F1={metrics['f1']:.4f}  (TP: {metrics['TP']}, FP: {metrics['FP']}, FN: {metrics['FN']})")
        
    print("\nLength mismatches: None (asserted by canonical decoder)")
    print(f"Truncation issues: {analysis['error_summary']['num_truncated_records']} records truncated by max_length")
    
    print("\nEvaluation consistency: PASS")
    
    # Generate NETWORK and HOSTINFO deep dive
    for target_cat in ["NETWORK", "HOSTINFO"]:
        print("\n" + "-"*50)
        print(f"--- {target_cat} DIAGNOSIS ---")
        print("-"*50)
        
        fp_examples = [ex for ex in analysis["false_positive_examples"] if ex["predicted"] == target_cat]
        fn_examples = [ex for ex in analysis["false_negative_examples"] if ex["actual"] == target_cat]
        wrong_cat_in = [ex for ex in analysis["wrong_category_examples"] if ex["predicted"] == target_cat]
        wrong_cat_out = [ex for ex in analysis["wrong_category_examples"] if ex["actual"] == target_cat]
        
        print(f"\n{target_cat} False Positives ({len(fp_examples)}): predicted {target_cat}, but was O")
        for ex in fp_examples[:10]:
            print(f"  - '{ex['text']}' in context: {' '.join(ex['tokens'])}")
            
        print(f"\n{target_cat} False Negatives ({len(fn_examples)}): was {target_cat}, but predicted O")
        for ex in fn_examples[:10]:
            print(f"  - '{ex['text']}' in context: {' '.join(ex['tokens'])}")
            
        print(f"\n{target_cat} Wrong Category (predicted {target_cat}, was something else):")
        for ex in wrong_cat_in[:10]:
            print(f"  - '{ex['text']}' (was {ex['actual']}) in context: {' '.join(ex['tokens'])}")
            
        print(f"\n{target_cat} Wrong Category (was {target_cat}, predicted something else):")
        for ex in wrong_cat_out[:10]:
            print(f"  - '{ex['text']}' (predicted {ex['predicted']}) in context: {' '.join(ex['tokens'])}")

    print("\n" + "="*50)
    print("NEXT STEP:")
    print("Only after PASS, decide whether Dataset v1.2 is required based on the diagnosis above.")
    print("="*50)

if __name__ == "__main__":
    run_analysis()
